# Split a complex vector `t` into a real matrix `T = [tᴿ -tᴵ; tᴵ tᴿ]`, whose real span is
# the complex span of `t` (in the re/im-doubled form `[tᴿ; tᴵ]` of coefficient vectors):
# with `α = αᴿ + iαᴵ`, the upper half of `T * [αᴿ, αᴵ]` is `real(αt)` and its lower half
# `imag(αt)`, since `αt = (αᴿtᴿ - αᴵtᴵ) + i(αᴿtᴵ + αᴵtᴿ)`. E.g., `split_complex([im, 0])`
# is `[0 -1; 0 0; 1 0; 0 0]`.
function split_complex(t::AbstractVector{<:Number})
    re_t, im_t = reim(t)
    return [re_t -im_t; im_t re_t]
end

@testset "AbstractArray interface" begin
    brs = bandreps(16, Val(2))
    cbr = @composite brs[3]
    tbm = tb_hamiltonian(cbr, [[0,0],[1,0]])
    @testset "AbstractArray indexing into TightBindingModel" begin
        @test length(tbm) == 4
        tbm_subset1 = tbm[1:3]
        tbm_subset2 = tbm[[1,2,3]]
        @test length(tbm_subset1) == 3
        @test tbm_subset1 == tbm_subset2
        tbm_subset3 = tbm[[1, 4]]
        @test length(tbm_subset3) == 2
        @test tbm_subset3[1] == tbm[1] && tbm_subset3[2] == tbm[4]

        # sub-selection preserves type
        @test typeof(tbm_subset1) == typeof(tbm_subset2) == typeof(tbm)
    end

    @testset "Concatenation of TightBindingModels (`vcat`)" begin
        @test vcat(tbm[1:2], tbm[3:4]) == tbm
        @test vcat(tbm[1:2], tbm[3:3]) == tbm[1:3]
        @test vcat(tbm[1:2], tbm[4:4]) != tbm
    end
end

