    end
end

@testset "≥ 2 Wyckoff position diagonal-block hermiticity-paired hoppings" begin
    # this is a corner-case related to the hermiticity-pairing of hoppings in an orbit;
    # previously, it was such that the 3rd term of `tbm` below could only be generated by
    # specifying `Rs` as containing _both_ `[1,0]` _and_ `[-1,0]`; this
    # only manifested in diagonal blocks featuring an EBR with more than one Wyckoff pos.
    
    # the test below checks that the term is generated always for `Rs` containing `[1,0]`
    # example is from docs/src/nonhermitian.md
    brs = bandreps(10, Val(2); timereversal = true)
    cbr = @composite brs[1] # (2c|A)
    tbm = tb_hamiltonian(cbr, [[1,0]])
    @test length(tbm) == 4
    tbt = tbm[3] # diagonally-directed hopping term, embodying the issue
    @test length(orbit(tbt.block.h_orbit)) == 4
    @test all(hops -> length(hops) == 2, tbt.block.h_orbit.hoppings)
    @test RVec{2}([3/2, -1/2]) ∈ orbit(tbt.block.h_orbit)

    # also check non-Hermitian counterpart: there are two off-diagonal hopping terms above
    # (the 3rd and 4th, which hop between the two distinct sites of the 2c Wyckoff position,
    # unlike the intra-site 1st and 2nd), each of which split under non-Hermitian conditions,
    # so we should have 4+2=6 terms
    tbm_NH = tb_hamiltonian(cbr, [[1,0]], Val(NONHERMITIAN))
    @test length(tbm_NH) == 6
end

@testset "Merging of hermiticity-related orbits with unequal hop counts" begin
    # a hopping orbit {δ} and its reversed orbit {-δ} can derive from different sets of
    # hops (a, b, R): here, without inversion, δ had 1 hop, -δ 2; merging them previously
    # did not add the missing hermitian-partner hops in `add_reversed_orbits!`, producing
    # an error in `construct_M_matrix`
    brs = bandreps(208) # P4₂32
    cbr = @composite brs[1] # (6f|A)
    tbm = tb_hamiltonian(cbr, [[1,0,0]])
    # check that we get the expected number of hopping terms (regression test)
    @test length(tbm) == 22
    # check that all orbits are equal length (i.e., "good")
    @test all(tbm) do tbt
        allequal(length.(tbt.block.h_orbit.hoppings))
    end
    # check that `tbm` is indeed Hermitian
    ptbm = tbm(cospi.(0.37 .* (1:length(tbm))))
    k = ReciprocalPoint([0.13, 0.27, 0.19])
    Hk = copy(ptbm(k))
    @test Hk ≈ Hk'
    # check that the Hamiltonian is symmetric for all symmetry operations
    @test all(primitivize(spacegroup(208))) do g
        D = site_induced_sgrep(ptbm, g)(k)
        gk = g * k
        isapprox(ptbm(gk), D * Hk * D'; atol = 1e-12)
    end
end

