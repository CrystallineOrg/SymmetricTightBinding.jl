# NB: The ordering of `t` is a bit subtle: `t` is a kind of vector-flattened
#        tensor `T`, with the following "indexing convention" for `T`:
#        1. The elements `T[i]` give a vector of hoppings corresponding to the `i`th orbit
#           `δᵢ = h_orbit.orbit[i]`. 
#        2. The elements `T[i][j]` give a vector of hoppings corresponding to the `j`th
#           possible spatial hopping with displacement `δᵢ`, associated with
#           `hᵢⱼ = h_orbit.hoppings[i][j]`.
#           This describes hoppings from site an "origin" `hᵢⱼ[1]` to a "destination"
#           `hᵢⱼ[2] + hᵢⱼ[3]` (where `hᵢⱼ[3]` is an integer "R" translation).
#        3. Finally, `T[i][j][k][m]` is a _single_ hopping term from the `k`-th partner
#           function of `hᵢⱼ[1]` site to the `m`-th partner function of `hᵢⱼ[2]` site.
#        If we are considering a diagonal block, i.e., `brₐ == brᵦ`, then we also have
#        to include the Hermitian or anti-Hermitian counterparts of each hopping term,
#        i.e., for each hopping term from `hᵢⱼ[1]` to `hᵢⱼ[2] + hᵢⱼ[3]`, we also have
#        to include the hopping term from `hᵢⱼ[2]` to `hᵢⱼ[1] - hᵢⱼ[3]`.

# NB: Time-reversal symmetry does NOT imply that if we have a hopping from q to w, we must
#     also have a hopping from w to q. This is a natural first assumption, but a false one.

#     As an example, consider a simple system with two sites, one at [0,0] and another at 
#     [2/3, 1/3]. Let us call `a` an orbital placed at [0,0] and `c` an orbital placed
#     at [2/3, 1/3]. Then, a possible Hamiltonian for first-nearest neighbors is: 
#        `H = \sum_𝐤 (α e^{i2π 𝐤·[-2/3, -1/3]} c_𝐤† a_𝐤 ± h.c.)`
#     where `±` accounts for hermiticity or anti-hermiticity. Let me prove that this
#     Hamiltonian is TRS iff `α` is real. Assume that the time-reversal operator
#     acts on the operators as: 𝒯 c_𝐤 𝒯⁻¹ = c_-𝐤, 𝒯 c_𝐤† 𝒯⁻¹ = c_-𝐤†; and the same for
#     `a_𝐤`. Then, applying the TRS operator to the Hamiltonian, we find:
#        `𝒯 H 𝒯⁻¹ = \sum_𝐤 (α* e^{-i2π 𝐤·[-2/3, -1/3]} c_-𝐤† a_-𝐤 ± h.c.)`
#     Changing the summation variable 𝐤 → -𝐤, we find:
#        `𝒯 H 𝒯⁻¹ = \sum_𝐤 (α* e^{i2π 𝐤·[-2/3, -1/3]} c_𝐤† a_𝐤 ± h.c.)`
#     Then, the only requirement for TRS is that `α = α*`, i.e., `α` is real.

#     This means that, in general, if we have a hopping from q to w, we don't need to
#     have a hopping from w to q.

#     The only terms where we need to consider reversed hoppings are the cases of blocks where
#     hermiticity or anti-hermiticity relates the block to itself: i.e., diagonal blocks. There,
#     if we have a hopping from q to w, we must also have a hopping from w to q, but they both
#     correspond to the same Wyckoff position and site-symmetry irrep, so the former discussion
#     holds.

# ---------------------------------------------------------------------------- #

"""
    OrbitalOrdering(br::BandRep{D}; allow_free::Bool = true) --> OrbitalOrdering{D}

Establishes a canonical, local ordering for the orbitals associated with a band representation
`br`. This is the default ordering used when associating row/column indices in a
tight-binding Hamiltonian block to specific orbitals in the associated band representations.

The canonical orbital ordering is stored in `.ordering`. The `i`th element of `ordering`,
`ordering[i]`, is a `NamedTuple` with three fields `wp`, `partner_idx`, and `site_idx`:
- `wp`: stores a Wyckoff position in the orbit of the Wyckoff position associated to
  `br`.
- `partner_idx`: stores the index of the partner function of the site-symmetry irrep
  associated to `br` at `wp`.
- `site_idx`: stores the index of `wp` in the orbit of `br`'s Wyckoff position (i.e., in
  `orbit(group(br))`, or, for a `o::OrbitalOrdering`, the unique, order-preserving
  subset of `[info.wp for info in o]`)

I.e., the `i`th orbital associated with `br` is located at `wp` and transforms as the
`partner_idx`th partner function of the site-symmetry irrep of `br.siteir`.
The total number of orbitals associated to a band representation, and hence the length of
`ordering`, is the product of the site-symmetry irrep dimensionality and the number of sites
in the Wyckoff position orbit.

The orbitals are ordered partner-function-major: i.e., the site index runs fastest, such
that the orbitals are `(site 1, partner 1), (site 2, partner 1), …, (site 1, partner 2), …`.
For spinful band representations, the Kramers partners of the first half of the partner
functions are the second half (cf. `timereversal_unitary`): so, in this ordering, time
reversal acts as `iσʸ ⊗ 𝟙` and the Hamiltonian has a pseudospin-block form.

All other orbital-ordering-dependent quantities derive from this ordering: the internal
block-level functions (e.g., `construct_M_matrix`, `site_induced_sgrep_excl_phase`, and
`site_induced_timereversal_unitary`) take the ordering of their block as an (optional)
argument, while the public, band representation-level functions (e.g., `orbital_positions`
and `site_induced_sgrep`) always use this canonical ordering.

## Keyword argument
- `allow_free::Bool` (default, `true`): passed to `primitivized_orbit`, determining whether
  to allow or disallow free parameters in orbit positions.
"""
function OrbitalOrdering(br::BandRep{D}; allow_free::Bool = true) where {D}
    wps = primitivized_orbit(br; allow_free) # free parameters are fine, unless disallowed

    V = length(wps)      # number of Wyckoff positions in orbit
    Q = irdim(br.siteir) # number of partner functions at each Wyckoff position
    ordering = Vector{OrbitalInfo{D}}(undef, V * Q)
    for partner_idx in 1:Q  # partner functions: outer (slow) index
        for site_idx in 1:V # sites: inner (fast) index
            wp = wps[site_idx]
            ordering[(partner_idx-1)*V+site_idx] = (; wp, partner_idx, site_idx)
        end
    end
    return OrbitalOrdering(ordering)
end

"""
    construct_M_matrix(
        h_orbit::HoppingOrbit{D}, br1::BandRep{D}, br2::BandRep{D},
        [ordering1, ordering2]) 
        --> Matrix{SparseMatrixCSC{Int, Int}}

Construct a set of matrices that encode a Hamiltonian term which resembles the hopping
from EBR `br1` to EBR `br2`.

The encoding `Mm` is stored as a matrix of sparse matrices, `Mm[s,t][i,j]`. Its first
indexing `[s,t]` corresponds to elements of the Bloch Hamiltonian Hₛₜ(𝐤). The second indexing
`[i,j]` instead corresponds such that the row index `i` matches to `orbit(h_orbit)[i]` and
the associated complex exponentials stored in `v[i]`, while the column index `j` matches to
the elements of the vector `t`. That is:

    Hₛₜ(k) = vᵢ(k) Mᵢⱼₛₜ tⱼ = vᵀ(k) Mm[s,t] t

See `devdocs.md` for details.
"""
function construct_M_matrix(
    h_orbit::HoppingOrbit{D},
    br1::BandRep{D},
    br2::BandRep{D},
    ordering1::OrbitalOrdering{D} = OrbitalOrdering(br1), # canonical orbital orderings for
    ordering2::OrbitalOrdering{D} = OrbitalOrdering(br2), # `br1` & `br2`, respectively
) where {D}
    V = length(orbit(h_orbit))
    E = length(first(h_orbit.hoppings)) # number of hopping terms per δᵢ (assumed constant for all i)
    foreach(h_orbit.hoppings) do hops
        if length(hops) ≠ E
            error("Unexpectedly had different counts of hoppings across orbit elements")
        end
    end
    Q1, Q2 = irdim(br1.siteir), irdim(br2.siteir)
    Q = Q1 * Q2

    # matrix of sparse matrices that will store the matrix-encoding for each Hamiltonian
    # element; each `Mm[α, β]` is a V×(V*E*Q) matrix of unit-elements
    Mm = Matrix{SparseMatrixCSC{Int, Int}}(undef, length(ordering1), length(ordering2))
    rs, cs = Int[], Int[] # row & column indices of unit-elements in `Mm[α, β]`
    for β in eachindex(ordering2), α in eachindex(ordering1)
        (q, i) = ordering1[α]
        (w, j) = ordering2[β]
        q = parent(q)
        w = parent(w)

        # assign a 1 to the correct position of WPs times irrep dimensionality
        for (r, hops) in enumerate(h_orbit.hoppings)
            offset0 = (r - 1) * E * Q
            for (x, hop) in enumerate(hops)
                q′, w′ = hop[1], hop[2]
                if (
                    isapprox(q′, q, nothing, false; atol = VEC_CMP_ATOL) &&
                    isapprox(w′, w, nothing, false; atol = VEC_CMP_ATOL)
                )
                    # an "ordinary" hopping, from `q` to `w`
                    offset1 = (x - 1) * Q
                    c = offset0 + offset1 + (j - 1) * Q1 + i
                    # set `Mm[α, β][r, c] = 1` by setting the row & column indices; `c`
                    # lies in `offset0 + offset1 .+ (1:Q)`, which is distinct for each
                    # pair of hop `x` & orbit element `r`, so `cs` is strictly increasing
                    push!(rs, r); push!(cs, c)
                end
            end
        end
        # use the `_sparse_with_unit_columns` instead of `sparse(rs, cs, 1, V, V * E * Q)`
        # in order to exploit that each column of `Mm[α, β]` has at most one unit-element
        # and that `cs` is strictly increasing
        Mm[α, β] = _sparse_with_unit_columns(rs, cs, V, V * E * Q)
        empty!(rs); empty!(cs)
    end

    return Mm
end

# build `sparse(rs, cs, 1, m, n)` directly in CSC form, exploiting (& assuming!) that each
# column of the input has at most one unit-element, and that the column indices `cs` are
# sorted, i.e., that `cs` is strictly increasing: this is faster than `sparse(rs, cs, 1, …)`;
# the input is *not* checked for these properties, so they must be ensured by the caller
function _sparse_with_unit_columns(rs::Vector{Int}, cs::Vector{Int}, m, n)
    colptr = zeros(Int, n + 1)
    colptr[1] = 1
    for c in cs
        colptr[c+1] = 1
    end
    cumsum!(colptr, colptr)
    rowval = copy(rs)
    nzval = ones(Int, length(rs))
    return SparseMatrixCSC(m, n, colptr, rowval, nzval)
end

"""
    coefficient_count(Mm::AbstractMatrix{SparseMatrixCSC{Int, Int}}) --> Int

Return the number `J` of (complex) hopping coefficients encoded by the M-matrix `Mm` (see
`construct_M_matrix`), i.e., the length of the coefficient vector `t` in
`Hₛₜ(k) = vᵀ(k) Mm[s,t] t`. Every `Mm[s,t]` is a V×J matrix (with `V` the number of hopping
vectors in the orbit), so `J` can be read off from any of them.
"""
coefficient_count(Mm::AbstractMatrix{SparseMatrixCSC{Int, Int}}) = size(first(Mm), 2)

# ---------------------------------------------------------------------------------------- #
# Constraints on the coefficient vector `t`
#
# All constraints on `t` (spatial symmetry, time-reversal, and hermiticity) are collected as
# rows of a single sparse, real constraint matrix `A` acting on the re/im-doubled coefficient
# vector `[tᴿ; tᴵ]` (with `t = tᴿ + i tᴵ`). The allowed coefficient vectors span the null
# space of `A`, which we obtain from its Gram matrix `AᵀA` (see `constraint_nullspace!`).
# In this formulation, constraints need not be deduplicated (repeated or collinear rows
# leave the null space unchanged), and the null space of several kinds of constraints is
# simply that of their combined rows.

"""
    ConstraintRows(J::Int)

`(i,j,v)` "triplet"-format of the rows of a sparse, real constraint matrix acting on the
re/im-doubled coefficient vector `[tᴿ; tᴵ]` (`2J` elements, with `t = tᴿ + i tᴵ`), intended
to accumulate constraints, block by block, via `add_constraints!` and
`add_complex_constraints!`; entries added repeatedly to the same element are summed.
The accumulated constraint matrix is obtained via `sparse(::ConstraintRows)` (or, consuming
the `ConstraintRows`, via `sparse!(::ConstraintRows)`).
"""
mutable struct ConstraintRows
    const J::Int              # no. of (complex) elements of `t` (half the no. of columns of realified constraint matrix)
    nrows::Int                # total no. of rows/constraints
    const is::Vector{Int}     # rows i
    const js::Vector{Int}     # columns j
    const vs::Vector{Float64} # nonzero values at [i,j]
end
ConstraintRows(J::Int) = ConstraintRows(J, 0, Int[], Int[], Float64[])

function SparseArrays.sparse(constraints::ConstraintRows)
    (; is, js, vs, nrows, J) = constraints
    return sparse(is, js, vs, nrows, 2J) # sums duplicate entries
end

"""
    sparse!(constraints::ConstraintRows) --> SparseMatrixCSC{Float64, Int}

Return the accumulated constraint matrix, as `sparse(constraints)`, but reusing the buffers
of `constraints` as the row-index and value storage of the returned matrix, rather than
allocating new ones.

!!! warning
    `constraints` is consumed: its buffers `is`, `js`, and `vs` are resized and overwritten
    to hold the returned matrix's data, so `constraints` no longer represents the
    constraints and must not be used afterwards.
"""
function SparseArrays.sparse!(constraints::ConstraintRows)
    (; is, js, vs, nrows, J) = constraints
    return sparse!(is, js, vs, nrows, 2J) # sums duplicate entries
end

"""
    RowPermutation(σ::Vector{Int})

A permutation matrix `Π` with `Π[σ[i], i] = 1`, stored (lazily) via the permutation `σ`.

Its product `Π * M` with a sparse matrix `M` is a `RowPermuted`, rather than a new sparse
matrix: the permutation of the rows, `(Π * M)[σ[i], :] = M[i, :]`, is only applied when the
product is added to a `ConstraintRows` (in a `RealConstraintTerm` or
`ComplexConstraintTerm`). `transpose(Π)` is the
inverse permutation, and `sparse(Π)` and `Matrix(Π)` materialize `Π`.
"""
struct RowPermutation
    σ::Vector{Int} # `Π[σ[i], i] = 1`
    function RowPermutation(σ::Vector{Int})
        isperm(σ) || throw(ArgumentError("input is not a permutation"))
        return new(σ)
    end
end
Base.size(Π::RowPermutation) = (length(Π.σ), length(Π.σ))
Base.size(Π::RowPermutation, d::Integer) = d ≤ 2 ? length(Π.σ) : 1
Base.transpose(Π::RowPermutation) = RowPermutation(invperm(Π.σ))
SparseArrays.sparse(Π::RowPermutation) = sparse(Π.σ, eachindex(Π.σ), one(Int), size(Π)...)
Base.Matrix(Π::RowPermutation) = Matrix(sparse(Π))

struct RowPermuted # `Π * M`, for `Π::RowPermutation`
    Π::RowPermutation
    M::SparseMatrixCSC{Int, Int}
end
function Base.:*(Π::RowPermutation, M::SparseMatrixCSC{Int, Int})
    size(Π, 2) == size(M, 1) || throw(DimensionMismatch("incompatible sizes of `Π` & `M`"))
    return RowPermuted(Π, M)
end
Base.size(A::RowPermuted, d...) = size(A.M, d...)

"""
    RealConstraintTerm(a::Real, b::Real, M)

A term `[a M  b M]` of a block of real constraint rows acting on `[tᴿ; tᴵ]` (see
`add_constraints!`), with `M` a V×J matrix: an element of `Mm` (a `SparseMatrixCSC`), or a
row permutation of one (`Π * M`, a `RowPermuted`).
"""
struct RealConstraintTerm{A <: Union{SparseMatrixCSC{Int, Int}, RowPermuted}}
    a::Float64 # coefficient of `M` acting on `tᴿ`
    b::Float64 # coefficient of `M` acting on `tᴵ`
    M::A
end
RealConstraintTerm(a::Real, b::Real, M::A) where {A} = RealConstraintTerm{A}(a, b, M)

"""
    ComplexConstraintTerm(c::Number, M)

A term `c M` of a block of complex constraint rows acting on the complex coefficient vector
`t` (see `add_complex_constraints!`), with `M` a V×J matrix: an element of `Mm` (a
`SparseMatrixCSC`), or a row permutation of one (`Π * M`, a `RowPermuted`).
"""
struct ComplexConstraintTerm{A <: Union{SparseMatrixCSC{Int, Int}, RowPermuted}}
    c::ComplexF64
    M::A
end
ComplexConstraintTerm(c::Number, M::A) where {A} = ComplexConstraintTerm{A}(c, M)

# push the nonzero entries of `x * M` to `constraints`, with their row & column indices
# offset by `row_offset` & `col_offset` (and the rows permuted by `σ`, if not `nothing`);
# `x = 0` would only add explicit zeros, so is skipped
function _push_scaled!(
    constraints::ConstraintRows,
    row_offset::Int,
    col_offset::Int,
    x::Real,
    M::SparseMatrixCSC{Int, Int},
    σ::Union{Nothing, Vector{Int}} = nothing,
)
    iszero(x) && return constraints
    rv, nzv = rowvals(M), nonzeros(M)
    for j in axes(M, 2), p in nzrange(M, j)
        i = isnothing(σ) ? rv[p] : σ[rv[p]]
        push!(constraints.is, row_offset + i)
        push!(constraints.js, col_offset + j)
        push!(constraints.vs, x * nzv[p])
    end
    return constraints
end
_push_scaled!(constraints, row_offset, col_offset, x, A::RowPermuted) =
    _push_scaled!(constraints, row_offset, col_offset, x, A.M, A.Π.σ)

"""
    add_constraints!(constraints::ConstraintRows, terms, [more_terms]) --> ConstraintRows

Append a block of `V` real constraint rows `Σₖ [aₖ Mₖ  bₖ Mₖ]`, acting on `[tᴿ; tᴵ]`, to
`constraints`. `terms` (nonempty) and `more_terms` are vectors or tuples of
`RealConstraintTerm`s, with coefficients `aₖ` & `bₖ` and `V×J` matrices `Mₖ`, all summed
into the same block. Two collections allow terms of different types (e.g., with and
without a row permutation) to be added together while each collection remains concretely
typed.
"""
function add_constraints!(constraints::ConstraintRows, terms, more_terms = ())
    V = size(first(terms).M, 1)
    _push_terms!(constraints, V, terms)
    _push_terms!(constraints, V, more_terms)
    constraints.nrows += V
    return constraints
end
function _push_terms!(constraints::ConstraintRows, V::Int, terms)
    (; J, nrows) = constraints
    for (; a, b, M) in terms::Union{AbstractVector{<:RealConstraintTerm},
                                     Tuple{Vararg{RealConstraintTerm}}}
        size(M) == (V, J) || throw(DimensionMismatch("terms must be V×J matrices"))
        _push_scaled!(constraints, nrows, 0, a, M) # `aₖ Mₖ`, acting on `tᴿ`
        _push_scaled!(constraints, nrows, J, b, M) # `bₖ Mₖ`, acting on `tᴵ`
    end
    return constraints
end

"""
    add_complex_constraints!(constraints::ConstraintRows, terms, [more_terms]) --> ConstraintRows

Append a block of `V` complex constraint rows `C = Σₖ cₖ Mₖ`, acting on the complex
coefficient vector `t`, to `constraints`. `terms` (nonempty) and `more_terms` are vectors or
tuples of `ComplexConstraintTerm`s, with complex coefficients `cₖ` and `V×J` matrices `Mₖ`,
all summed into the same block (cf. `add_constraints!`).

The rows are added in realified form, i.e., as the `2V` real rows of `[Re(C) -Im(C);
Im(C) Re(C)]`, acting on `[tᴿ; tᴵ]`: `C t = 0` is equivalent to `Re(C) tᴿ - Im(C) tᴵ = 0`
and `Im(C) tᴿ + Re(C) tᴵ = 0`.
"""
function add_complex_constraints!(constraints::ConstraintRows, terms, more_terms = ())
    V = size(first(terms).M, 1)
    _push_complex_terms!(constraints, V, terms)
    _push_complex_terms!(constraints, V, more_terms)
    constraints.nrows += 2V
    return constraints
end
function _push_complex_terms!(constraints::ConstraintRows, V::Int, terms)
    (; J, nrows) = constraints
    for (; c, M) in terms::Union{AbstractVector{<:ComplexConstraintTerm},
                                  Tuple{Vararg{ComplexConstraintTerm}}}
        size(M) == (V, J) || throw(DimensionMismatch("terms must be V×J matrices"))
        # NB: `cₖ` is often purely real or imaginary, so some of these are skipped
        _push_scaled!(constraints, nrows,     0,  real(c), M) # Re(C) tᴿ
        _push_scaled!(constraints, nrows,     J, -imag(c), M) # -Im(C) tᴵ
        _push_scaled!(constraints, nrows + V, 0,  imag(c), M) # Im(C) tᴿ
        _push_scaled!(constraints, nrows + V, J,  real(c), M) # Re(C) tᴵ
    end
    return constraints
end

"""
    constraint_nullspace!(constraints::ConstraintRows; atol::Real) --> Matrix{Float64}

Return an orthonormal basis (as columns) for the null space of the constraint matrix
`A = sparse(constraints)`, i.e., for the coefficient vectors `[tᴿ; tᴵ]` that satisfy every
constraint. `constraints` is consumed in the process (see `sparse!(::ConstraintRows)`).

The null space is obtained from that of the Gram matrix `AᵀA`, via a pivoted Cholesky
factorization (see `psd_nullspace!`), treating pivots below `atol²` as zero: since the
eigenvalues of `AᵀA` are the squared singular values of `A`, this roughly corresponds to
treating singular values of `A` below `atol` as zero, as in `nullspace(A; atol)`. `AᵀA`
is only 2J×2J, whereas `A` typically has many more rows than columns.
"""
function constraint_nullspace!(constraints::ConstraintRows; atol::Real)
    A = sparse!(constraints)
    G = Symmetric(Matrix(A' * A))
    # `A` & `G = AᵀA` share their null space (`Gx = 0` ⇒ `‖Ax‖² = xᵀGx = 0`); `G` is only
    # 2J×2J and positive semi-definite, so its null space is cheaply found by a pivoted
    # Cholesky factorization (cheaper, and more robust for the degenerate null eigenvalues,
    # than partial eigensolvers; and much cheaper than an SVD of the tall `A`). Working with
    # `G` squares `A`'s condition number, which is harmless here: `A`'s nonzero singular
    # values lie in ~[1, 5] (empirically, across all space groups), far from `atol`.
    return psd_nullspace!(G; tol = atol^2)
end

"""
    add_symmetry_constraints!(
        constraints::ConstraintRows,
        Mm::AbstractMatrix{SparseMatrixCSC{Int, Int}},
        h_orbit::HoppingOrbit{D},
        brₐ::BandRep{D},
        brᵦ::BandRep{D},
        gens::AbstractVector{<:AbstractOperation{D}},
       [orderingₐ::OrbitalOrdering{D} = OrbitalOrdering(brₐ),
        orderingᵦ::OrbitalOrdering{D} = OrbitalOrdering(brᵦ)]
    ) --> ConstraintRows

Add the constraints imposed on `t` by the spatial symmetries `gens` to `constraints`.

We have constructed the representation matrices such that gΦ(k) = ρᵀ(g)Φ(Rk); then, the
Hamiltonian transforms under symmetries as H(g𝐤) = ρₐₐ(g) H(𝐤) ρᵦᵦ⁺(g). The left-hand
side, H(g𝐤), is equivalent to permuting the elements of `v` (and hence the rows of each
`Mm[s,t]`; see `_permute_symmetry_related_hoppings_under_symmetry_operation`) as
Hₛₜ(g𝐤) = vᵀ(𝐤) Pᵀ M⁽ˢᵗ⁾ t. The right-hand side is

(ρₐₐ)ᵣₛ Hₛₜ (ρᵦᵦ⁻¹)ₜₗ = (ρₐₐ)ᵣₛ vᵢ Mᵢⱼₛₜ tⱼ (ρᵦᵦ⁻¹)ₜₗ = vᵢ (ρₐₐ)ᵣₛ Mᵢⱼₛₜ (ρᵦᵦ⁻¹)ₜₗ tⱼ,

i.e., vᵀ(𝐤) Q⁽ʳˡ⁾ t with Q⁽ʳˡ⁾ = Σₛₜ (ρₐₐ)ᵣₛ (ρᵦᵦ⁻¹)ₜₗ M⁽ˢᵗ⁾. Hence, `t` must satisfy
(Q⁽ʳˡ⁾ - Pᵀ M⁽ʳˡ⁾) t = 0 for every generator and every `(r,l)`; each row of
`Q⁽ʳˡ⁾ - Pᵀ M⁽ʳˡ⁾` is a complex constraint on `t`, added to `constraints` in realified form.

The sum over `s,t` runs only over the nonzero elements of `ρₐₐ` and `ρᵦᵦ`: as these are
block-permutation-like matrices, each Q⁽ʳˡ⁾ is a combination of only a few M⁽ˢᵗ⁾.
"""
function add_symmetry_constraints!(
    constraints::ConstraintRows,
    Mm::AbstractMatrix{SparseMatrixCSC{Int, Int}},
    h_orbit::HoppingOrbit{D},
    brₐ::BandRep{D},
    brᵦ::BandRep{D},
    gens::AbstractVector{<:AbstractOperation{D}},
    orderingₐ::OrbitalOrdering{D} = OrbitalOrdering(brₐ),
    orderingᵦ::OrbitalOrdering{D} = OrbitalOrdering(brᵦ),
) where {D}
    ρsₐₐ = site_induced_sgrep_excl_phase.(Ref(brₐ), gens, Ref(orderingₐ))
    ρsᵦᵦ = if brₐ == brᵦ # might as well reuse, if same BR
        ρsₐₐ
    else
        site_induced_sgrep_excl_phase.(Ref(brᵦ), gens, Ref(orderingᵦ))
    end

    Q_terms = ComplexConstraintTerm{SparseMatrixCSC{Int, Int}}[] # reused for each block
    for (op, ρₐₐ, ρᵦᵦ) in zip(gens, ρsₐₐ, ρsᵦᵦ)
        Pᵀ = _permute_symmetry_related_hoppings_under_symmetry_operation(h_orbit, op)
        for l in axes(Mm, 2), r in axes(Mm, 1)
            # Q⁽ʳˡ⁾ - Pᵀ M⁽ʳˡ⁾, with Q⁽ʳˡ⁾ = Σₛₜ (ρₐₐ)ᵣₛ (ρᵦᵦ)*ₗₜ M⁽ˢᵗ⁾ (nonzero terms only)
            empty!(Q_terms)
            append!(Q_terms, (ComplexConstraintTerm(ρₐₐ[r, s] * conj(ρᵦᵦ[l, t]), Mm[s, t])
                              for s in axes(ρₐₐ, 2) if !iszero(ρₐₐ[r, s])
                              for t in axes(ρᵦᵦ, 2) if !iszero(ρᵦᵦ[l, t])))
            add_complex_constraints!(constraints, Q_terms,
                                     (ComplexConstraintTerm(-1, Pᵀ * Mm[r, l]),))
        end
    end
    return constraints
end

"""
    obtain_basis_free_parameters(
        h_orbit::HoppingOrbit{D},
        brₐ::BandRep{D}, 
        brᵦ::BandRep{D}, 
       [orderingₐ = OrbitalOrdering(brₐ), 
        orderingᵦ = OrbitalOrdering(brᵦ),
        diagonal_block::Bool = true,
        hermiticity::Hermiticity = HERMITIAN]
    )              --> Tuple{Matrix{SparseMatrixCSC{Int, Int}}, Vector{Vector{Float64}}}

Obtain the basis of free parameters for the hopping terms between `brₐ` and `brᵦ` 
associated with the hopping orbit `h_orbit`.

## Note

The presence or absence of time-reversal symmetry is inferred implicitly from `brₐ` and `brᵦ`.
"""
function obtain_basis_free_parameters(
    h_orbit::HoppingOrbit{D},
    brₐ::BandRep{D},
    brᵦ::BandRep{D},
    orderingₐ::OrbitalOrdering{D} = OrbitalOrdering(brₐ),
    orderingᵦ::OrbitalOrdering{D} = OrbitalOrdering(brᵦ),
    diagonal_block::Bool = true,
    hermiticity::Hermiticity = HERMITIAN,
) where {D}
    num(brₐ) == num(brᵦ) || error("input `BandRep`s must come from the same space group")
    brₐ.timereversal == brᵦ.timereversal || error("input `BandRep`s must have identical time-reversal symmetry")
    timereversal = brₐ.timereversal

    # generators in a primitive basis (double group generators, for spinful band
    # representations)
    gens = primitivized_generators(brₐ)

    # encode Hamiltonian as a coefficient matrix sandwiched by exponentials & hopping ampl.
    Mm = construct_M_matrix(h_orbit, brₐ, brᵦ, orderingₐ, orderingᵦ)

    # actual computation
    tₐᵦ_basis_reim = _obtain_basis_free_parameters(
        h_orbit,
        brₐ,
        brᵦ,
        orderingₐ,
        orderingᵦ,
        Mm,
        gens,
        timereversal,
        diagonal_block,
        hermiticity,
    )

    return Mm, tₐᵦ_basis_reim
end

function _obtain_basis_free_parameters(
    h_orbit::HoppingOrbit{D},
    brₐ::BandRep{D},
    brᵦ::BandRep{D},
    orderingₐ::OrbitalOrdering{D},
    orderingᵦ::OrbitalOrdering{D},
    Mm::AbstractMatrix{SparseMatrixCSC{Int, Int}},
    gens::AbstractVector{<:AbstractOperation{D}},
    timereversal::Bool,
    diagonal_block::Bool,
    hermiticity::Hermiticity,
) where {D}
    # collect all constraints on the coefficient vector `t` associated with `h_orbit`, as
    # rows of a real constraint matrix acting on the re/im-doubled vector `[tᴿ; tᴵ]`: we
    # want to work with strictly real coefficients for the basis vectors, so we split the
    # possible products of complex coefficients with a complex basis vector into two
    # vectors, where the lower half of each represents the imaginary part of the product.
    # A benefit of this is that it becomes possible to take the complex conjugate of each
    # element "symbolically" by simply multiplying with [1 0; 0 -1] (block matrix), which
    # is needed for the time-reversal and hermiticity constraints. Crucially, this must be
    # kept in mind everywhere that we use a coefficient vector. In particular, we must
    # always interpret `Mm` as acting like `[Mm iMm]` on a "doubled" basis vector.
    constraints = ConstraintRows(coefficient_count(Mm))

    # spatial symmetry constraints on Hₐᵦ
    add_symmetry_constraints!(constraints, Mm, h_orbit, brₐ, brᵦ, gens, orderingₐ, orderingᵦ)

    # time-reversal constraints
    if timereversal
        add_timereversal_constraints!(constraints, Mm, brₐ, brᵦ, orderingₐ, orderingᵦ)
    end

    # hermiticity constraints, if this is a diagonal block
    if diagonal_block && hermiticity ≠ NONHERMITIAN
        antihermitian = hermiticity === ANTIHERMITIAN
        add_hermiticity_constraints!(constraints, Mm, h_orbit, antihermitian)
    end

    # the allowed coefficient vectors span the null space of the combined constraints
    tₐᵦ_basis_reim_matrix = constraint_nullspace!(constraints; atol = NULLSPACE_ATOL_DEFAULT)
    isempty(tₐᵦ_basis_reim_matrix) && return Vector{Vector{Float64}}()

    # ------------------------------------------------------------------------------------ #
    # Make sure we have a reasonably pretty-looking basis in the end by sparsifying and
    # dropping near-zero elements explicitly

    # convert null-space to a sparse column form
    tₐᵦ_basis_reim_matrix_form′ = _poormans_sparsification(tₐᵦ_basis_reim_matrix)
    tₐᵦ_basis_reim = [collect(v) for v in eachcol(tₐᵦ_basis_reim_matrix_form′)]

    # prune near-zero elements of basis vectors
    _prune_at_threshold!(tₐᵦ_basis_reim)

    return tₐᵦ_basis_reim
end

"""
Build the P matrix for a particular symmetry operation acting on k-space, whose transpose
`Pᵀ` permutes the rows of the M matrix; `Pᵀ` (not `P`) is returned, as a `RowPermutation`.

To obtain the P matrix, we exploit that the action is on exponentials of the type
``exp(-2πi𝐤⋅δ)``, and instead act on δ ∈ `h_orbit.orbit` rather than on k. Because of this,
we need to use the inverse of the rotation part of the symmetry operation.

!!! details "Sketch of proof"
    Assume g={R|τ} and `Crystalline` implements gk=(R⁻¹)ᵀk. Then
    (gk)⋅δ = ((R⁻¹)ᵀk)⋅δ + τ = k⋅(R⁻¹)δ.

!!! info
    It is assumed that the operation `op` is provided in a primitive setting.

!!! warning
    This function is an internal helper function for `add_symmetry_constraints!` and
    `add_hermiticity_constraints!` and is not part of the public API.
"""
function _permute_symmetry_related_hoppings_under_symmetry_operation(
    h_orbit::HoppingOrbit{D},
    op::AbstractOperation{D}, # only the rotation part is used
) where {D}
    # P is a square matrix that acts as `op` on `v`, i.e., represents ``op ∘ v``, via a
    # matrix-vector product `P*v`. Equivalently, `P` can act on `M` (via its transpose)
    # for expressions of the kind (Pv)ᵀ M … = vᵀ Pᵀ M …
    
    N = length(orbit(h_orbit))
    cols = Vector{Int}(undef, N) # `P[i, cols[i]] = 1`, i.e., the nonzero column of each row
    for (i, δᵢ) in enumerate(orbit(h_orbit))
        # crystalline implements gk = [R⁻¹]ᵀk. However, since we don't have access to k,
        # being a symbolic variable, we will translate its action into δ. For this,
        # we implement a simple trick: ([R⁻¹]ᵀ k)·r = R⁻¹ᵢⱼ kᵢ rⱼ = k·(R⁻¹ r)
        R⁻¹ = SymOperation(inv(rotation(op))) # rotation-only part of `op`
        δᵢ′ = compose(R⁻¹, δᵢ)
        j = findfirst(orbit(h_orbit)) do δ′′
            isapprox(δᵢ′, δ′′, nothing, false; atol = VEC_CMP_ATOL)
        end
        isnothing(j) &&
            error(lazy"hopping element $δᵢ not closed under $op in $(orbit(h_orbit))")
        cols[i] = j
        # since P acts as g v = P v, we have (gv)ᵢ = vⱼ = ∑ₖ Pᵢₖ vₖ so Pᵢₖ = δᵢⱼ
    end
    # since `Π[σ[j], j] = 1` for a `Π::RowPermutation`, `cols` directly gives `Pᵀ`, which
    # is what callers need (`Pᵀ[cols[i], i] = P[i, cols[i]] = 1`)
    Pᵀ = RowPermutation(cols)
    return Pᵀ
end

"""
Poor man's "matrix sparsification" via the reduced row echelon form.

!!! warning
    This function is an internal helper function for `obtain_basis_free_parameters` and
    is not part of the public API.
"""
function _poormans_sparsification(
    A::AbstractMatrix{<:Number};
    rref_tol::Union{Nothing, Float64} = SPARSIFICATION_ATOL_DEFAULT,
)
    # following appendix E of the Qsymm paper (https://arxiv.org/abs/1806.08363) [copied
    # over from Neumann.jl] [copied over from MPBUtils.jl]
    if !isnothing(rref_tol)
        # use a relatively low tolerance in `rref` to avoid explosions of errors
        # NB: this optional tolerance argument of `rref!` is undocumented :(
        return transpose(rref!(copy(transpose(A)), rref_tol))
    end
    return transpose(rref(transpose(A)))
end

"""
Prune near-zero elements of vectors in `vs`.

!!! warning
    This function is an internal helper function for `obtain_basis_free_parameters` and
    is not part of the public API.
"""
function _prune_at_threshold!(
    vs::AbstractVector{<:AbstractVector{T}};
    atol::Real = PRUNE_ATOL_DEFAULT,
) where {T <: Complex}
    for v in vs
        for (j, vⱼ) in enumerate(v)
            rⱼ, iⱼ = reim(vⱼ)
            rⱼ′ = ifelse(abs(rⱼ) < atol, zero(real(T)), rⱼ)
            iⱼ′ = ifelse(abs(iⱼ) < atol, zero(real(T)), iⱼ)
            v[j] = T(rⱼ′, iⱼ′)
        end
    end
    return vs
end

function _prune_at_threshold!(
    vs::AbstractVector{<:AbstractVector{T}};
    atol::Real = PRUNE_ATOL_DEFAULT,
) where {T <: Real} # needed for type consistency in TRS implementation
    for v in vs
        for (j, vⱼ) in enumerate(v)
            v[j] = abs(vⱼ) < atol ? zero(T) : vⱼ
        end
    end
    return vs
end

