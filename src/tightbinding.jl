"""
    add_reversed_orbits!(h_orbits::Vector{HoppingOrbit{D}}) where {D}

Adds the reversed hopping terms to the hopping orbits in `h_orbits`. The reversed
hopping terms are added to the orbit of the hopping term they are related to; if they are
already present in another orbit, the two orbits are merged.

It is assumed that this functionality will only be called for diagonal blocks.
"""
function add_reversed_orbits!(
    h_orbits::Vector{HoppingOrbit{D}}
) where {D}
    # for any orbit that contains a hopping vector `δ`, we check if its reversed
    # hopping vector `-δ` is also in the orbit; if not, we check if it is in any other
    # orbit to merge them, and, if not, we add it manually to the orbit

    # below, we assume that if, for some δ, no counterpart is found, then no other δ in the
    # orbit has a counterpart, so we can just add it manually

    # determine if `h_orbit`s should be modified
    for (n, h_orbit) in enumerate(h_orbits)
        δs = orbit(h_orbit) # δs in the current orbit

        # check whether the orbit is already "good" (i.e., all δs have a -δ counterpart)
        if all(δ -> isapproxin(-δ, δs, nothing, false; atol = VEC_CMP_ATOL), δs)
            # all δs have a -δ counterpart in the orbit: nominally, the orbit is good as-is,
            # but the hermitian-partner hops might still be missing; so `add_reversed_hops!`
            # checks for this and adds any missing "reversed hops"
            _add_reversed_hops!(h_orbit)
            continue # the orbit is now properly closed: nothing to merge & we continue
        end

        merge_idx = findfirst(@view h_orbits[n+1:end]) do h_orbit′
            isapproxin(-δs[1], orbit(h_orbit′), nothing, false; atol = VEC_CMP_ATOL)
        end
        if !isnothing(merge_idx)
            # at least one δ has a -δ counterpart in another orbit - we need to merge them
            # NB: We assume that if one δ has a -δ counterpart in another orbit, then all
            #     δs in the orbit have a -δ counterpart in the same orbit, so we merge them
            n′ = something(merge_idx) + n
            h_orbit′ = h_orbits[n′]

            # merge the orbits
            append!(h_orbit.orbit, h_orbit′.orbit)
            append!(h_orbit.hoppings, h_orbit′.hoppings)

            # the hops at δ and -δ that we just merged came from different (a, b, R) sets,
            # so the hermitian-partner hops may be missing on either side; so we need to
            # call `_add_reversed_hops!` once more to make sure (this e.g., touched sg208
            # models at 6f `Rs = [[1,0,0]]`, where δ had 1 hop, and -δ had 2)
            _add_reversed_hops!(h_orbit)

            # remove the merged orbit
            deleteat!(h_orbits, n′)
            continue
        end
        # we now know that at least some δ doesn't have a -δ counterpart; we assume that
        # this implies that none of the δs have a -δ counterpart, so we need to add them all
        @assert all(δ -> !isapproxin(-δ, δs, nothing, false; atol = VEC_CMP_ATOL), δs)

        # first append the new δs into the orbit
        append!(δs, -δs)

        # add the "reversed" hopping terms: i.e., for every hop with tuple (a, b, R) we add
        # the reversed tuple (b, a, -R); with δ = a - b - R, the reversed tuple has
        # displacement b - a - (-R) = -(a - b - R) = -δ, which is why we appended -δs above
        hoppings = h_orbit.hoppings
        hoppings′ = map(hoppings) do hops
            map(hops) do (qₐ, qᵦ, R)
                (qᵦ, qₐ, -R) # reverse the hopping term
            end
        end
        append!(hoppings, hoppings′)
    end
    return h_orbits
end

# For every hop a → b + R at δ in `h_orbit`, ensure that its hermitian partner ("reversed
# hop") b → a - R is included at -δ: this is not guaranteed automatically, as -δ may have
# entered the orbit through a symmetry operation (or merge) that does not correspond to this
# hermitian-partner ("reversed hop") relationship. NB: the function implicitly assumes
# that every δ has a -δ counterpart in `h_orbit` (violating this is UB).
function _add_reversed_hops!(h_orbit::HoppingOrbit)
    δs = orbit(h_orbit)
    # no. of original hops at each δ: the loop below only appends to `h_orbit.hoppings[…]`,
    # so the original hops remain the first `nhops[idx]` elements of each
    nhops = map(length, h_orbit.hoppings)
    for (idx, δ) in enumerate(δs)
        idx′ = something(findfirst(δs) do δ′
            isapprox(-δ, δ′, nothing, false; atol = VEC_CMP_ATOL)
        end)
        hops = h_orbit.hoppings[idx]
        hops′ = h_orbit.hoppings[idx′]
        for k in 1:nhops[idx]
            (qₐ, qᵦ, R) = hops[k]
            rev_hop = (qᵦ, qₐ, -R) # reverse hop
            rev_qₐ, rev_qᵦ, rev_R = rev_hop
            has_counterpart = any(hops′) do hop′
                qₐ′, qᵦ′, R′ = hop′
                (isapprox(rev_qₐ, qₐ′, nothing, false; atol = VEC_CMP_ATOL) &&
                 isapprox(rev_qᵦ, qᵦ′, nothing, false; atol = VEC_CMP_ATOL) &&
                 isapprox(rev_R,  R′,  nothing, false; atol = VEC_CMP_ATOL))
            end
            has_counterpart || push!(hops′, rev_hop)
        end
    end
end

# for NONHERMITIAN models, hermiticity no longer links a hop `a → b+R` to its conjugate
# hop `b → a-R`; but, in presenting the hopping terms, a user would usually expect to
# see both kinds of hopping families be included if one is - even though they end up as
# separate terms: to ensure this, we add -R to Rs if it is not already in Rs (insert -R
# immediately after R if not already present)
function _augment_with_negative_counterparts(Rs)
    Rs′ = empty!(similar(Rs)) # empty vector with suitable backing size
    for R in Rs
        push!(Rs′, R)
        R_neg = -R
        if !isapproxin(R_neg, Rs; atol = VEC_CMP_ATOL)
            push!(Rs′, R_neg)
        end
    end
    return Rs′
end
