"""
    obtain_symmetry_related_hoppings(
        Rs::AbstractVector{V}, 
        brₐ::BandRep{D}, 
        brᵦ::BandRep{D};
        diagonal_block::Bool = true,
        reverse_hop::Bool = false,
        nonhermitian::Bool = false
    ) --> Vector{HoppingOrbit{D}}

Compute the symmetry-related hopping terms from the points in the WP of `brₐ` to the 
WP of `brᵦ`, displaced by a set of primitive lattice-vector representatives `Rs`.

## Implementation
1. Take a point `a` in the WP of `brₐ` and a point `b` in the WP of `brᵦ`. 
    Compute the displacement vector `δ = a - b - R`, where `R ∈ Rs`, giving the displacement
    vector from `b + R` (annihilated site) to `a` (created site): i.e., `δ` points along
    the hopping direction (from annihilated to created site).
2. If `δ ∈ representatives`, add `δ => (a, b, R)` to the list of hoppings 
    for that representative and continue. Otherwise, search all representatives for one 
    whose list of hoppings contains `δ => (a, b, R)`. If none is found, add `δ` as a new 
    representative and add `δ => (a, b, R)` to its list of hoppings.
3. Take `g ∈ generators`, compute `δ' = g δ` and `(a', b', R') = (g a, g b, g R)`, 
    and repeat step 2.
4. Repeat steps 1–3 for all pairs of points in the WPs of `brₐ` and `brᵦ`.

Additionally, if we are considering a diagonal block (which must be Hermitian or anti-Hermitian),
we check whether orbits that relate `δ` and `-δ` are present; if not, we add them.
"""
function obtain_symmetry_related_hoppings(
    Rs::AbstractVector{V}, # must be specified in the primitive basis
    brₐ::BandRep{D},
    brᵦ::BandRep{D};
    diagonal_block::Bool = true, # whether to manually add "reversed" hoppings (if true),
    reverse_hop::Bool = false, # if hopping actually goes from a+R→b rather than a→b+R
                               # (used in NONHERMITIAN case, for lower-triangular blocks)
                               # practically just corresponds to flipping signs of `Rs`
    nonhermitian::Bool = false # whether to assume the model is NONHERMITIAN: if false,
                               # we assume HERMITIAN or ANTIHERMITIAN and add & merge
                               # reversed hoppings explicitly; if true (NONHERMITIAN), we
                               # augment every R by -R if diagonal_block is true, to ensure
                               # that we include both "sides" of terms that _would be_
                               # related by Hermitcity (but don't merge them)
) where {V <: Union{AbstractVector{<:Integer}, RVec{D}}} where {D}
    sgnum = num(brₐ)
    num(brᵦ) == sgnum || error("input `BandRep`s must belong to the same space group")
    brₐ.timereversal == brᵦ.timereversal || error("input `BandRep`s must have the same time-reversal symmetry")

    # work in a primitive basis, for both operations and the Wyckoff positions' orbits; the
    # latter then contain no positions related by centering translations
    ops = primitivize(spacegroup(sgnum, Val{D}()))
    wpsₐ = primitivized_orbit(brₐ; allow_free = true)
    wpsᵦ = primitivized_orbit(brᵦ; allow_free = true)

    # we have defined a structure `HoppingOrbit` to gather the information. It is 
    # structured as:
    # 1. `HoppingOrbit.representatives` will store a representative hopping vector δ
    # 2. `HoppingOrbit.orbit` will store the full orbit of symmetry related hopping 
    #   vector generated by δ: {δᵢ}
    # 3. `HoppingOrbit.hoppings` will store the real coordinates `(a,b,R)` of each 
    #   hopping term associated to each `δᵢ`. Note that maybe several `(a,b,R)` could be 
    #   associated to the same `δᵢ`

    # in the non-Hermitian case, we augment Rs by -Rs if we are in a diagonal block, to
    # ensure we return both "sides" of terms that _would be_ related by Hermiticity;
    # this effectuates a functionality similar to having `reverse_hop` equal to both true
    # _and_ false
    # the reason we need to do this explicitly in the nonhermitian case, is that without
    # hermiticity, we are no longer guaranteed that a hop `a → b+R` links to its conjugate
    # hop `b → a-R`; but a user would usually expect to see both "sides" of such a paired
    # term appear in a returned listing (even though they end up as separate terms); so we
    # augment to ensure this (and the augmenting is only necessary in the diagonal_block,
    # as `reverse_hop` is passed as `true` by `tb_hamiltonian` for non-diagonal blocks)
    if diagonal_block && nonhermitian
        reverse_hop && error("unexpected input combination: `reverse_hop = true`, `nonhermitian = true`, & `diagonal_block = true`")
        Rs = _augment_with_negative_counterparts(Rs)
    end

    h_orbits = HoppingOrbit{D}[]
    for R in Rs
        reverse_hop && (R = -R) # treat as hopping from a+R→b (equivalently, from a→b-R)
        R = RVec{D}(R) # change the type of R for type consistency
        for (qₐ, qᵦ) in Iterators.product(wpsₐ, wpsᵦ)
            qₐ = parent(qₐ) # work with RVec directly rather than Wyckoff Position
            qᵦ = parent(qᵦ)
            δ = qₐ - qᵦ - R # potential representative in next element of `h_orbits`
            maybe_add_hoppings!(h_orbits, δ, qₐ, qᵦ, R, ops)
        end
    end

    # hermiticity/anti-hermiticity could link orbits that spatial symmetries might not have
    # already linked: in particular, if we are in a "diagonal block" of the Hamiltonian,
    # then, for every hopping vector `δ`, we must have a "reversed" counterpart `-δ` in the
    # presence of hermiticity or anti-hermiticity; but those two vectors might have fallen
    # in distinct orbits up this point - if so, we now merge them
    if diagonal_block && !nonhermitian
        add_reversed_orbits!(h_orbits)
    end

    # finally, sort the elements of each orbit into a canonical order (see
    # `sort_orbit_by_sign_pairs!`): this is purely cosmetic, but makes for nicer default
    # printing of the associated Hamiltonian terms
    foreach(sort_orbit_by_sign_pairs!, h_orbits)

    return h_orbits
end

"""
    maybe_add_hoppings!(h_orbits, δ, qₐ, qᵦ, R, ops) --> Vector{HoppingOrbit{D}}

Checks whether a hopping term `δ` is already in the list of representatives. If not, adds it
and its symmetry-related partners. If it is, only the symmetry-related partners are added.
"""
function maybe_add_hoppings!(
    h_orbits,
    δ,
    qₐ,
    qᵦ,
    R,
    ops::AbstractVector{SymOperation{D}},
) where {D}
    δ_idx = findfirst(h_orbits) do h_orbit
        # check if δ is in existing h_orbits
        isapproxin(δ, orbit(h_orbit), nothing, false; atol = VEC_CMP_ATOL)
    end
    if isnothing(δ_idx)
        # if it wasn't already in `h_orbits`, we add it and its symmetry-related partners
        δ_orbit = HoppingOrbit{D}(δ, [δ], [[(qₐ, qᵦ, R)]])
        push!(h_orbits, δ_orbit)
    else # if it was already in `h_orbits`, we only add its symmetry-related partners
        δ_orbit = h_orbits[δ_idx]
    end
    _maybe_add_hoppings!(δ_orbit, δ, qₐ, qᵦ, R, ops)
end

"""
Computes and adds the symmetry related partners of a hopping term `δ` to the `δ_orbit`.

!!! warning
    This function is an internal helper function for `maybe_add_hoppings!` and
    is not part of the public API.
"""
function _maybe_add_hoppings!(
    δ_orbit,
    δ,
    qₐ,
    qᵦ,
    R,
    ops::AbstractVector{SymOperation{D}},
) where {D}
    for g in ops
        _qₐ′ = g * qₐ
        _qᵦ′ = g * (qᵦ + R)
        # _qₐ′ and _qᵦ′ can include a translation part that is a multiple of the lattice
        # translation, so we reduce it to a unit range & keep the translation part separate
        qₐ′ = RVec(reduce_translation_to_unitrange(constant(_qₐ′)), free(_qₐ′))
        qᵦ′ = RVec(reduce_translation_to_unitrange(constant(_qᵦ′)), free(_qᵦ′))
        dₐ = _qₐ′ - qₐ′ # possible lattice translation part of _qₐ′
        dᵦ = _qᵦ′ - qᵦ′ # possible lattice translation part of _qᵦ′

        R′ = dᵦ - dₐ # total lattice translation part of the symmetry-related hopping term δ'
        g_rotation = SymOperation(rotation(g)) # rotation-only part of g
        δ′ = g_rotation * δ # potential symmetry related partner of `δ` to add to `δ_orbit`

        # several sanity checks:
        #   1. R´ is a lattice translation, i.e., it is integer
        #   2. R´ doesn't have any free parameters
        #   3. δ′ = qₐ′ - qᵦ′ - R′
        all(Rᵢ′ -> abs(Rᵢ′ - round(Rᵢ′)) < VEC_CMP_ATOL, constant(R′)) ||
            error("arrived at non-integer lattice translation R′: should be impossible")
        isspecial(R′) || error(
            "arrived at non-special (nonzero free parameters) lattice translation R′: should be impossible",
        )
        isapprox(δ′, qₐ′ - qᵦ′ - R′, nothing, false; atol = VEC_CMP_ATOL) ||
            error("δ′ ≠ qₐ′ - qᵦ′ - R′")

        idx_in_orbit = findfirst(orbit(δ_orbit)) do δ′′
            isapprox(δ′, δ′′, nothing, false; atol = VEC_CMP_ATOL)
        end
        if isnothing(idx_in_orbit)
            # δ′ is not already included in `orbit(δ_orbit)`
            push!(orbit(δ_orbit), δ′)
            push!(δ_orbit.hoppings, [(qₐ′, qᵦ′, R′)])
        else
            # δ′ already in `orbit(δ_orbit)` but hopping term might not be: evaluate
            # `(qₐ′, qᵦ′, R′) ∉ δ_orbit.hoppings[idx_in_orbit]`, w/ approx. comparison
            bool = !any(δ_orbit.hoppings[idx_in_orbit]) do (qₐ′′, qᵦ′′, R′′)
                    isapprox(qₐ′, qₐ′′, nothing, false; atol = VEC_CMP_ATOL) &&
                    isapprox(qᵦ′, qᵦ′′, nothing, false; atol = VEC_CMP_ATOL) &&
                    isapprox(R′, R′′, nothing, false; atol = VEC_CMP_ATOL)
                end
            if bool
                push!(δ_orbit.hoppings[idx_in_orbit], (qₐ′, qᵦ′, R′))
            end
        end
    end
    return δ_orbit
end

