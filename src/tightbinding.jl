"""
    tb_hamiltonian(
        cbr::CompositeBandRep{D},
        Rs::AbstractVector{Vector{Int}}
        [Sᵛ::Val{S} = Val(HERMITIAN)]
    ) -> TightBindingModel{D, S}

Construct the tight-binding Hamiltonian from a given composite band representation `cbr` and
a set of global translation-representatives `Rs`.

Whether the returned Hamiltonian is Hermitian, anti-Hermitian, or non-Hermitian can be
controlled by passing the optional argument `Sᵛ :: Val{S}` where `S` is an value of the enum
type [`Hermiticity`](@ref), i.e., `HERMITIAN`, `ANTIHERMITIAN`, or `NONHERMITIAN` (default,
`HERMITIAN`).
This choice can also be passed a plain `S` (without a `Val` wrapper) but the call is then
not type-stable.
For `NONHERMITIAN` models, `Rs` is interpreted to also include `-Rs`: this ensures that the
returned hopping terms always feature "both sides" of Hermiticity-related pairs of terms.

Both spinless (single-valued) and spinful (double-valued) models are supported; the choice
follows directly from the spin properties of `cbr` (a spinful model can be built from
`bandreps(sgnum; spinful = Val(true))`).

The returned [`TightBindingModel`](@ref) will generally feature several terms (iterating to
[`TightBindingTerm`](@ref)s), each representing a tight-binding term that is closed under
the symmetry operations of the underlying space group.

## Kramers partners in time-reversal symmetric spinful settings

For spinful models with time-reversal symmetry, the model follows Crystalline.jl convention
for the unitary part of time reversal (iσʸK, see Crystalline's `timereversal_unitary`):
for a `2n`-dimensional site irrep, partner functions `i` and `i+n` are Kramers partners
(i.e., time-reversal conjugate states). Since the orbitals of each band representation are
ordered partner-function-major (see [`OrbitalOrdering`](@ref)), this makes orbitals `m` and
`m+nV` Kramers partners, for a band representation with `V` sites (counting `m` from the
start of the band representation's block in the Hamiltonian). Thus, time reversal acts on
each pair (`m`, `m+nV`) exactly as on the spin-up and -down states of a spin-½ (i.e., as
iσʸK), and each block of the Hamiltonian (between a pair of band representations) has a
2×2 pseudospin-block form. The pair can therefore be thought of as |↑⟩ and |↓⟩ pseudospin
states; if the site orbitals carry no intrinsic spin-orbit coupling, this is just the
electron's spin.
"""
function tb_hamiltonian(
    cbr::CompositeBandRep{D, IR, SIR},
    Rs::AbstractVector{<:AbstractVector{Int}} = [zeros(Int, D)], # "global" hopping translation-representatives
    Sᵛ::Val{S} = Val(HERMITIAN),
) where {D, S, IR, SIR}
    if any(c -> !isinteger(c) || c < 0, cbr.coefs)
        error("the input composite band representation does not have a symmetric \
               tight-binding model: its expansion in EBRs contain negative or \
               fractional coefficients")
    end
    if !(S isa Hermiticity)
        error(lazy"hermiticity type `S` must be a value of the `Hermiticity` enum: was $S")
    end
    coefs = round.(Int, cbr.coefs)

    # find all bandreps featured in the composite bandrep and build a "repeated" entry list
    brs = Vector{BandRep{D, IR, SIR}}(undef, sum(coefs))
    idx = 0
    for (i, c) in enumerate(coefs)
        for _ in 1:c
            brs[idx+=1] = cbr.brs[i]
        end
    end

    if any(br -> !iszero(free(position(br))), brs)
        error("free parameters in Wyckoff positions are not supported; any non-special \
               Wyckoff position must have its free parameters pinned to a definite value \
               prior to calling `tb_hamiltonian`: see `pin_free!`")
    end

    # find all families of hoppings between involved band representations: the TB model will
    # be divided into each of these representatives since they will be symmetry independent
    axis = BlockArrays.BlockedOneTo((cumsum(occupation(br) for br in brs)))
    tbs = Vector{TightBindingTerm{D, S, IR, SIR}}()
    for block_info in _block_iterates(brs, Rs, Sᵛ)
        (; block_ij, br1, br2, ordering1, ordering2, diagonal_block, h_orbits) = block_info
        for h_orbit in h_orbits
            Mm, t_αβ_basis = obtain_basis_free_parameters(
                h_orbit,
                br1,
                br2,
                ordering1,
                ordering2,
                diagonal_block,
                S,               #=hermiticity=#
            )
            for t in t_αβ_basis
                block = TightBindingBlock{D, S}(
                    br1,
                    br2,
                    ordering1,
                    ordering2,
                    h_orbit,
                    Mm,
                    t,
                    diagonal_block
                )
                h = TightBindingTerm(
                    axis,
                    block_ij,
                    block,
                    brs,
                )
                push!(tbs, h)
            end
        end
    end

    return TightBindingModel(tbs, cbr)
end

# For HERMITIAN/ANTIHERMITIAN: iterate over only non-negative diagonals (negative diagonals
# follow from hermiticity/anti-hermiticity)
_diagonal_indices(B::Int, ::Val{S}) where {S} = 0:B-1
_row_indices(B::Int, d::Int, ::Val{S}) where {S} = 1:B-d
# For NONHERMITIAN: iterate over all diagonal, including positive and negative ones, and do
# it in the order 0, 1, -1, 2, -2, …, B-1, -(B-1)
_diagonal_indices(B::Int, ::Val{NONHERMITIAN}) = (iseven(i) ? -(i÷2) : (i+1)÷2 for i in 0:2(B-1))
_row_indices(B::Int, d::Int, ::Val{NONHERMITIAN}) = d ≥ 0 ? (1:B-d) : (-d+1:B)

"""
    _block_iterates(brs, Rs, ::Val{S})

Iterate over the blocks of a tight-binding model over the band representations `brs`, each
given as a `(; block_ij, br1, br2, ordering1, ordering2, diagonal_block, h_orbits)`, with
`h_orbits` the block's hopping orbits over the translation representatives `Rs`.

Blocks are listed diagonal by diagonal, from the main diagonal and up: this gives a natural
sorting of the terms of a model, with self-hoppings first, etc.
For Hermitian and anti-Hermitian models (`S`), only the upper triangular blocks are
included, the lower following from (anti-)Hermiticity; for non-Hermitian models, all blocks
are included, going along diagonals 0, 1, -1, …, B-1, -(B-1).

!!! warning
    This function is an internal helper function for `tb_hamiltonian` and
    `subduced_complement`, and is not part of the public API.
"""
function _block_iterates(brs::AbstractVector{<:BandRep}, Rs, Sᵛ::Val{S}) where {S}
    B = length(brs)
    # equivalent to `for d in …; for block_i in …`: `d` is the outer (slow) index
    block_ijs = ((block_i, block_i + d)
                 for d in _diagonal_indices(B, Sᵛ)       # outer: diagonals
                 for block_i in _row_indices(B, d, Sᵛ))  # inner: rows along diagonal `d`
    return Iterators.map(block_ijs) do (block_i, block_j)
        br1, br2 = brs[block_i], brs[block_j]
        diagonal_block = block_i == block_j
        reverse_hop = S === NONHERMITIAN && block_i > block_j # lower-triangular block
        h_orbits = obtain_symmetry_related_hoppings(
            Rs, br1, br2; diagonal_block, reverse_hop, nonhermitian = S === NONHERMITIAN
        )
        (; block_ij = (block_i, block_j), br1, br2,
           ordering1 = OrbitalOrdering(br1), ordering2 = OrbitalOrdering(br2),
           diagonal_block, h_orbits)
    end
end

function tb_hamiltonian(
    cbr::CompositeBandRep, Rs::AbstractVector{<:AbstractVector{Int}}, S::Hermiticity
) 
    return tb_hamiltonian(cbr, Rs, Val(S))
end
